CREATE TABLE IF NOT EXISTS stock(company TEXT, branch TEXT, qty INTEGER NOT NULL CHECK(qty>=0), PRIMARY KEY(company,branch));
CREATE TABLE IF NOT EXISTS commands(id TEXT PRIMARY KEY, fingerprint TEXT NOT NULL, doc TEXT NOT NULL, remaining INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS documents(id TEXT PRIMARY KEY, qty INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS journal(doc TEXT, account TEXT, debit INTEGER NOT NULL, credit INTEGER NOT NULL, PRIMARY KEY(doc,account));
CREATE TABLE IF NOT EXISTS outbox(id TEXT PRIMARY KEY);
